class Command(BaseCommand):
    help = 'بارگذاری دیتابیس اولیه داروها'

    def handle(self, *args, **options):
        self.stdout.write('در حال بارگذاری دسته‌بندی‌ها...')
        cat_map = {}
        for name, desc, icon in CATEGORIES:
            cat, created = DrugCategory.objects.get_or_create(
                name=name,
                defaults={'description': desc, 'icon': icon}
            )
            cat_map[name] = cat
            if created:
                self.stdout.write(f'  ✔ دسته: {name}')

        self.stdout.write('در حال بارگذاری داروها...')
        count = 0
        for (name, name_en, generic, cat_name, form, dosage,
             desc, symptoms, side_effects, warnings, is_otc) in DRUGS:
            cat = cat_map.get(cat_name)
            drug, created = Drug.objects.get_or_create(
                name=name,
                defaults={
                    'name_en':      name_en,
                    'generic_name': generic,
                    'category':     cat,
                    'form':         form,
                    'dosage':       dosage,
                    'description':  desc,
                    'symptoms':     symptoms,
                    'side_effects': side_effects,
                    'warnings':     warnings,
                    'is_otc':       is_otc,
                }
            )
            if created:
                count += 1

        self.stdout.write(self.style.SUCCESS(
            f'\n✅ {count} دارو و {len(cat_map)} دسته‌بندی با موفقیت بارگذاری شد!'
        ))